def _png_grey(arr_u8: np.ndarray) -> bytes:
    h, w = arr_u8.shape
    raw = b"".join(b"\x00" + arr_u8[r].tobytes() for r in range(h))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9))
            + chunk(b"IEND", b""))


def _hillshade(z, mask):
    """Sun azimuth 315 deg (compass), altitude 45 deg, same for every terrain (10.6)."""
    zf = np.where(mask & np.isfinite(z), z, 0.0)
    dz_drow, dz_dcol = np.gradient(zf, L_VIS)
    dzdx = dz_dcol             # east
    dzdn = -dz_drow            # north (rows grow southward)
    nx, ny, nz = -dzdx, -dzdn, np.ones_like(zf)
    norm = np.sqrt(nx * nx + ny * ny + nz * nz)
    az, alt = math.radians(315.0), math.radians(45.0)
    sx, sy, sz = math.sin(az) * math.cos(alt), math.cos(az) * math.cos(alt), math.sin(alt)
    shade = np.clip((nx * sx + ny * sy + nz * sz) / norm, 0, 1)
    img = np.rint(shade * 255).astype(np.uint8)
    img[~mask] = 0
    return img


