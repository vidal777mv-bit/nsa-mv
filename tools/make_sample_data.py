def _unlocked_atlas(created, sha):
    """Writes coverage/<body>.json, atlas/mars_cells.json and discoveries.json (SAMPLE). Returns the cells."""
    earth_list = []
    seen = set()
    for t in TARGETS:
        for aid, _kind, _seed, alat, alon, aname in t["analogs"]:
            if aid not in seen:
                seen.add(aid)
                earth_list.append((aid, alat, alon, aname))
    rng = np.random.default_rng(SEED + 13)
    cells = _sample_cells(rng, earth_list)

    mars_pts = [(t["lat"], t["lon"]) for t in TARGETS if t["body"] == "mars"] + [(c["lat"], c["lon"]) for c in cells]
    moon_pts = [(t["lat"], t["lon"]) for t in TARGETS if t["body"] == "moon"]
    earth_pts = [(a[1], a[2]) for a in earth_list]
    coverage = {
        "mars": (mars_pts, _band_around(mars_pts, 6.0)),
        "moon": (moon_pts, lambda LAT, LON: LAT <= -80.0),
        "earth": (earth_pts, lambda LAT, LON: np.abs(LAT) <= 25.0),
    }
    for body, (pts, to_discover) in coverage.items():
        _write_compact(OUT / "coverage" / f"{body}.json", {
            "body": body, "res_deg": 1, "width": COV_W, "height": COV_H, "origin": [-180, 90],
            "classes": {"0": "out_of_reach", "1": "to_discover", "2": "unlocked"},
            "grid": _cover_grid(pts, to_discover),
            "source": "SAMPLE: synthetic coverage around the sample sites (not the real CTX, LOLA or WorldCover extent).",
            "sample": True,
            **({"notes": MARS_NOTES} if body == "mars" else {}),
        })

    _write_json(OUT / "atlas" / "mars_cells.json", cells)

    twin_ids = {a[0] for t in TARGETS for a in t["analogs"]} | {tw["analog_id"] for c in cells for tw in c["twins"]}
    nov_by_id = {aid: _novelty(alat, alon) for aid, alat, alon, _n in earth_list}
    new_ids = sorted(i for i in twin_ids if nov_by_id[i][0] == "new")
    known_ids = sorted(i for i in twin_ids if nov_by_id[i][0] == "known_region")
    _write_json(OUT / "discoveries.json", {
        "schema": f"{SCHEMA_PREFIX}.discoveries/1", "sample": True,
        "earth_windows_scanned": SAMPLE_POOL_SIZE,
        "mars_cells_unlocked": len(cells),
        "new_twins": len(new_ids),
        "known_region_twins": len(known_ids),
        "new_twin_ids": new_ids,
        "known_regions": KNOWN_REGIONS,
        "definition": "new_twins = unique Earth windows that are a top-3 twin of any Mars/Moon target or Mars atlas cell and whose novelty is new.",
        "provenance": _prov("discoveries", created, sha),
    })
    return cells


def main():
    created = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    sha = hashlib.sha256((ROOT / "config" / "measure.json").read_bytes()).hexdigest()

    OUT.mkdir(parents=True, exist_ok=True)

    # 1. terrains (built once, reused by cards)
    built = {}
    for tid, (kind, seed) in TERRAIN_KIND_SEED.items():
        built[tid] = _build_terrain(kind, seed * 1000 + 7)
        b = built[tid]
        body, name, lat, lon = TERRAIN_META[tid]
        tdir = OUT / "terrain" / tid
        tdir.mkdir(parents=True, exist_ok=True)
        zv = b["zv"]
        finite = zv[b["mv"]]
        (tdir / "height.bin").write_bytes(zv.astype("<f4").tobytes(order="C"))
        # Earth analogs may be compared with targets on both bodies.
        layer_bodies = ("mars", "moon") if body == "earth" else (body,)
        for layer_body in layer_bodies:
            (tdir / f"layers_{layer_body}.bin").write_bytes(b["layers"].astype(np.uint8).tobytes(order="C"))
        (tdir / "hillshade.png").write_bytes(_png_grey(_hillshade(zv, b["mv"])))
        _write_json(tdir / "meta.json", {
            "id": tid, "body": body, "name": name, "lat": lat, "lon": lon,
            "n": N_VIS, "L": L_VIS, "R": R,
            "z_min": float(finite.min()), "z_max": float(finite.max()),
            "source_id": "SAMPLE_synthetic",
            "layers": {lb: f"layers_{lb}.bin" for lb in layer_bodies},
            "sample": True,
            "provenance": _prov("terrain", created, sha, {"note": "Synthetic terrain, closed-form. Not NASA data."}),
        })

    # 2. targets + rankings + cards
    target_index = []
    for t in TARGETS:
        tid = t["id"]
        tb = built[tid]
        scored = []
        for aid, _kind, _seed, alat, alon, aname in t["analogs"]:
            ab = built[aid]
            D, z = _dist(tb["feats"], ab["feats"])
            rot = _best_rotation(tb["zv"], ab["zv"])
            ve = _pair_ve(tb["zv"], tb["mv"], ab["zv"], ab["mv"])
            nov, kr = _novelty(alat, alon)
            scored.append({"aid": aid, "name": aname, "lat": alat, "lon": alon, "novelty": nov, "known_region_id": kr, "D": D,
                           "z": z, "rot": rot, "ab": ab, "ve": ve})
        scored.sort(key=lambda s: (s["D"] is None, s["D"] if s["D"] is not None else 0))

        ranking_rows, prev_D, gcount = [], None, 0
        for rank, s in enumerate(scored, start=1):
            if prev_D is None or (s["D"] - prev_D) >= V1_P95_D:
                gcount += 1
            prev_D = s["D"]
            s["rank"], s["tie"] = rank, gcount - 1
            ranking_rows.append({"rank": rank, "analog_id": s["aid"], "D": s["D"], "tie_group": gcount - 1,
                                 "lat": s["lat"], "lon": s["lon"],
                                 "card": f"cards/{tid}__{s['aid']}.json",
                                 "analog_place": _place(s["name"]),
                                 "novelty": s["novelty"], "known_region_id": s["known_region_id"]})

        _write_json(OUT / "rankings" / f"{tid}.json", {
            "schema": f"{SCHEMA_PREFIX}.rankings/1", "target_id": tid, "sample": True,
            "note": "SAMPLE ranking of 3 synthetic analogs. D is not a result.",
            "provenance": _prov("rankings", created, sha), "ranking": ranking_rows})

        for s in scored:
            ab = s["ab"]
            feats = {}
            for k in FEATURES:
                tv, av = tb["feats"][k], ab["feats"][k]
                feats[k] = {"target": tv, "analog": av,
                            "z_diff": None if (tv is None or av is None) else (av - tv) / SAMPLE_SIGMA[k]}
            zs = {k: feats[k]["z_diff"] for k in FEATURES}
            similar = [k for k in IN_DISTANCE if zs[k] is not None and abs(zs[k]) <= 1]
            different = [k for k in IN_DISTANCE if zs[k] is not None and abs(zs[k]) > 1]
            context_similar = [k for k in CONTEXT_FEATURES if zs[k] is not None and abs(zs[k]) <= 1]
            context_different = [k for k in CONTEXT_FEATURES if zs[k] is not None and abs(zs[k]) > 1]
            src = "SAMPLE placeholder limit (not a mission value); replace from config/missions.json"
            card = {
                "target_id": tid, "analog_id": s["aid"], "rank": s["rank"], "D": s["D"],
                "tie_group": s["tie"],
                "features": feats,
                "in_distance": IN_DISTANCE, "context_features": CONTEXT_FEATURES,
                "similar": similar, "different": different,
                "context_similar": context_similar, "context_different": context_different,
                "vertical_exaggeration": s["ve"],
                "novelty": s["novelty"], "known_region_id": s["known_region_id"],
                "context": _context(s["aid"]),
                "analog_place": _place(s["name"]),
                "mission_pct": {
                    "landing": {"target": tb["landing_pct"], "analog": ab["landing_pct"],
                                "limit_deg": LANDING_LIMIT_DEG, "source": src},
                    "driving": {"target": tb["driving_pct"], "analog": ab["driving_pct"],
                                "limit_deg": DRIVING_LIMIT_DEG, "source": src},
                },
                "rotation_deg": s["rot"],
                "files": {"target": f"terrain/{tid}/", "analog": f"terrain/{s['aid']}/"},
                "provenance": _prov("cards", created, sha, {
                    "baseline_m": L_MEAS,
                    "note": "Slope measured at 100 m baseline. Rotation does not change the score.",
                    "sample_sigma": SAMPLE_SIGMA,
                    "mission_pct_denominator": "pixels with a defined slope (100 m grid, inside the 8 km disk)",
                }),
            }
            if s["rank"] == 1:   # SAMPLE refined search (STANDARDS 10.13): one offset per target
                card["refined_offset_km"] = [2.0, -4.0]
                card["refined_D_before"] = round(s["D"] + 0.12, 4)
                card["refined_D_after"] = s["D"]
            _write_json(OUT / "cards" / f"{tid}__{s['aid']}.json", card)

