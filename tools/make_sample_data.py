def _sinusoid_field(rng, amp_std, wl_min, wl_max, count, beta):
    """Closed-form random field: sum of cosines, power-law amplitudes, std ~= amp_std."""
    wl = np.exp(rng.uniform(np.log(wl_min), np.log(wl_max), count))
    k = 2 * np.pi / wl
    theta = rng.uniform(0, 2 * np.pi, count)
    phase = rng.uniform(0, 2 * np.pi, count)
    amp = (k / k.min()) ** (-beta)
    amp *= amp_std / math.sqrt(np.sum(amp ** 2) / 2)
    return k * np.cos(theta), k * np.sin(theta), phase, amp


def _eval_field(field, X, Y):
    kx, ky, ph, a = field
    z = np.zeros_like(X)
    for i in range(len(a)):
        z += a[i] * np.cos(kx[i] * X + ky[i] * Y + ph[i])
    return z


def _terrain_fn(kind: str, seed: int):
    """Return f(X, Y) in metres (x east, y north) for one synthetic terrain kind."""
    rng = np.random.default_rng(seed)
    if kind == "crater":
        rb, depth, rim_h, rim_w = 1800.0, 280.0, 90.0, 260.0
        noise = _sinusoid_field(rng, 12.0, 250.0, 2500.0, 60, 1.2)

        def f(X, Y):
            r = np.hypot(X, Y)
            bowl = -depth * np.clip(1 - (r / rb) ** 2, 0, None)
            rim = rim_h * np.exp(-(((r - rb) / rim_w) ** 2))
            return bowl + rim + _eval_field(noise, X, Y)
        return f
    if kind == "ridges":
        period, amp = 700.0, 110.0
        ang = 0.6
        noise = _sinusoid_field(rng, 10.0, 150.0, 1200.0, 50, 1.0)

        def f(X, Y):
            u = X * math.cos(ang) + Y * math.sin(ang)
            return amp * (1 - np.abs(np.sin(math.pi * u / period))) + _eval_field(noise, X, Y)
        return f
    if kind == "volcanic":
        noise = _sinusoid_field(rng, 45.0, 120.0, 1800.0, 80, 0.8)
        cones = []
        for _ in range(5):
            cones.append((rng.uniform(-2500, 2500), rng.uniform(-2500, 2500),
                          rng.uniform(220, 420), rng.uniform(90, 180)))

        def f(X, Y):
            z = _eval_field(noise, X, Y)
            for cx, cy, s, H in cones:
                z += H * np.exp(-((X - cx) ** 2 + (Y - cy) ** 2) / (2 * s * s))
            return z
        return f
    if kind == "plain":
        noise = _sinusoid_field(rng, 2.5, 800.0, 3000.0, 40, 1.5)

        def f(X, Y):
            return _eval_field(noise, X, Y)
        return f
    raise ValueError(kind)


def _grid(n, L):
    c = (n - 1) // 2
    jj, ii = np.meshgrid(np.arange(n), np.arange(n))
    X = (jj - c) * L
    Y = (c - ii) * L
    mask = np.hypot(X, Y) <= R
    return X, Y, mask


def _disk_mean(z, mask):
    return float(np.mean(z[mask]))


def _slope_deg(z):
    """Central differences only where the 4 neighbours are valid (STANDARDS 4)."""
    zp = np.pad(z, 1, constant_values=np.nan)
    gy, gx = np.gradient(zp, L_MEAS)
    gy, gx = gy[1:-1, 1:-1], gx[1:-1, 1:-1]
    return np.degrees(np.arctan(np.hypot(gx, gy))), gx, gy


def _tpi(z):
    """z minus the mean over the annulus 0 < d <= r_px; NaN unless the full annulus is valid."""
    p = TPI_R_PX
    zp = np.pad(z, p, constant_values=np.nan)
    n = z.shape[0]
    total = np.zeros_like(z)
    count = 0
    for di in range(-p, p + 1):
        for dj in range(-p, p + 1):
            if 0 < di * di + dj * dj <= p * p:
                total = total + zp[p + di:p + di + n, p + dj:p + dj + n]
                count += 1
    return z - total / count


def _features(z):
    """The six measured features on the 100 m grid (STANDARDS section 4)."""
    slope, gx, gy = _slope_deg(z)
    out = {}
    sv = slope[np.isfinite(slope)]
    out["slope_p95_deg"] = float(np.percentile(sv, 95)) if sv.size >= 50 else None

    zz = z[np.isfinite(z)]
    p5, p95 = np.percentile(zz, [5, 95])
    out["hi"] = float(np.clip((zz.mean() - p5) / (p95 - p5), 0, 1)) if (p95 - p5) >= 1e-6 else None

    ok = np.isfinite(gx) & np.isfinite(gy)
    if ok.sum() >= 50:
        a, b, c = np.mean(gx[ok] ** 2), np.mean(gx[ok] * gy[ok]), np.mean(gy[ok] ** 2)
        l2, l1 = np.linalg.eigvalsh(np.array([[a, b], [b, c]]))
        s = l1 + l2
        out["coherence"] = 0.0 if s < 1e-12 else float((l1 - l2) / s)
    else:
        out["coherence"] = None

    lags, nus = [1, 2, 4, 8], []
    for k in lags:
        dx = z[:, k:] - z[:, :-k]
        dy = z[k:, :] - z[:-k, :]
        sq = np.concatenate([dx[np.isfinite(dx)] ** 2, dy[np.isfinite(dy)] ** 2])
        nus.append(math.sqrt(sq.mean()) if sq.size else 0.0)
    if all(nu > 0 for nu in nus):
        out["hurst"] = float(np.polyfit(np.log(lags), np.log(nus), 1)[0])
    else:
        out["hurst"] = None

    tpi = _tpi(z)
    tv = tpi[np.isfinite(tpi)]
    if tv.size:
        out["ridge_pct"] = float(100 * np.mean(tv > TPI_T))
        out["valley_pct"] = float(100 * np.mean(tv < -TPI_T))
    else:
        out["ridge_pct"] = out["valley_pct"] = None
    return out, slope, tpi


def _mission_pct(slope, limit):
    valid = np.isfinite(slope)
    return float(100 * np.mean(slope[valid] <= limit)) if valid.any() else None


def _build_terrain(kind: str, seed: int):
    """Returns the 30 m visual height, the 100 m measurement height and derived arrays."""
    fn = _terrain_fn(kind, seed)
    Xv, Yv, mv = _grid(N_VIS, L_VIS)
    zv = np.where(mv, fn(Xv, Yv), np.nan)
    offset = _disk_mean(zv, mv)
    zv = zv - offset

    Xm, Ym, mm = _grid(N_MEAS, L_MEAS)
    zm = np.where(mm, fn(Xm, Ym) - offset, np.nan)

    feats, slope, tpi = _features(zm)
    bits = ((slope > LANDING_LIMIT_DEG).astype(np.uint8) * 1
            | (slope > DRIVING_LIMIT_DEG).astype(np.uint8) * 2
            | (tpi > TPI_T).astype(np.uint8) * 4
            | (tpi < -TPI_T).astype(np.uint8) * 8)
    # nearest-neighbour upsample 100 m -> 30 m (section 10.6)
    xs = (np.arange(N_VIS) - C_VIS) * L_VIS
    idx = np.clip(np.rint(xs / L_MEAS).astype(int) + C_MEAS, 0, N_MEAS - 1)
    layers = bits[np.ix_(idx, idx)].astype(np.uint8)
    layers[~mv] = 0

    return {
        "zv": zv, "mv": mv, "zm": zm, "mm": mm,
        "feats": feats, "slope": slope, "layers": layers,
        "landing_pct": _mission_pct(slope, LANDING_LIMIT_DEG),
        "driving_pct": _mission_pct(slope, DRIVING_LIMIT_DEG),
    }


def _best_rotation(target_z, analog_z):
    """Alignment rotation 0-350 step 10 minimising RMS of standardised heights, r <= 0.9 R (10.6).

    The analog is sampled at R(theta) p for every target pixel p (nearest neighbour, sample only;
    the website samples bilinearly, which only changes the picture, not the stored angle).
    """
    X, Y, _ = _grid(N_VIS, L_VIS)
    inner = np.hypot(X, Y) <= 0.9 * R
    xi, yi, tz = X[inner], Y[inner], target_z[inner]
    best = None
    for deg in range(0, 360, 10):
        th = math.radians(deg)
        c, s = math.cos(th), math.sin(th)
        xs_, ys_ = xi * c - yi * s, xi * s + yi * c
        fi = np.rint(C_VIS - ys_ / L_VIS).astype(int)
        fj = np.rint(C_VIS + xs_ / L_VIS).astype(int)
        ok = (fi >= 0) & (fi < N_VIS) & (fj >= 0) & (fj < N_VIS)
        av = np.full(xi.shape, np.nan)
        av[ok] = analog_z[fi[ok], fj[ok]]
        both = np.isfinite(tz) & np.isfinite(av)
        if both.sum() < 50:
            continue
        a, b = tz[both], av[both]
        a = (a - a.mean()) / (a.std() or 1.0)
        b = (b - b.mean()) / (b.std() or 1.0)
        rms = float(np.sqrt(np.mean((a - b) ** 2)))
        if best is None or rms < best[1]:
            best = (deg, rms)
    return best[0]


