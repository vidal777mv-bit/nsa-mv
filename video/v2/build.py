def ridge(z, base_y, amp_px, width=1920, height=1080):
    lo, hi = min(z), max(z)
    n = len(z)
    pts = []
    for i, v in enumerate(z):
        x = i / (n - 1) * width
        y = base_y - (v - lo) / ((hi - lo) or 1) * amp_px
        pts.append(f"{x:.1f},{y:.1f}")
    return "M0," + str(height) + " L" + " L".join(pts) + f" L{width},{height} Z"


